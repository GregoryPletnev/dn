#!/usr/bin/env python3
"""Generate src/dnpalettes.inc from the Dos Navigator 1.51 color palettes.

Input: assets/palettes/*.PAL, unmodified copies of COLORS/*.PAL from
https://www.ritlabs.com/download/dn/dn151.zip (Dos Navigator 1.51,
Copyright (c) 1991-99 RIT Research Labs). File layout: a length byte and
that many TV attribute bytes (the TApplication palette), a color-index
block, then 'VGAP' + 48 bytes of VGA DAC (16 red, 16 green, 16 blue,
6-bit), then 'BLNK' + the blink flag.
"""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'palettes')
OUT = os.path.join(ROOT, 'src', 'dnpalettes.inc')

# order shown in Options > Fonts/Colors; id, file, menu name
ORDER = [
    ('default',  'DEFAULT.PAL',  'DN default'),
    ('norton',   'NORTON.PAL',   'Norton Commander'),
    ('blue',     '_BLUE.PAL',    'DN blue (VGA)'),
    ('dark',     'DARK.PAL',     'Dark'),
    ('spring',   '_SPRING.PAL',  'Spring (VGA)'),
    ('dosshell', 'DOSSHELL.PAL', 'MS-DOS Shell'),
    ('pctools',  'PCTOOLS.PAL',  'PC Tools / Norton Utilities'),
    ('vax',      'VAX.PAL',      'Green terminal (VAX)'),
    ('bw',       'BW.PAL',       'Black & white'),
    ('vgabw',    '_BW.PAL',      'Black & white (VGA mono)'),
    ('mono',     'MONO.PAL',     'Monochrome'),
]


def parse(path):
    b = open(path, 'rb').read()
    n = b[0]
    attrs = list(b[1:1 + n])
    i = 1 + n
    i += 1 + b[i]                      # color-index block
    dac = None
    if b[i:i + 4] == b'VGAP':
        d = b[i + 4:i + 52]
        dac = [(d[c], d[16 + c], d[32 + c]) for c in range(16)]
        i += 52
    blink = b[i + 4] if b[i:i + 4] == b'BLNK' else 0
    return attrs, dac, blink


def main():
    out = ['{ generated by scripts/gen-palettes.py from assets/palettes/*.PAL --',
           '  Dos Navigator 1.51 color palettes, Copyright (c) 1991-99 RIT',
           '  Research Labs. Based on Dos Navigator by RIT Research Labs. }',
           'const',
           '  DnPalCount = %d;' % len(ORDER),
           '  DnPalettes: array[0..DnPalCount - 1] of TDnPalette = (']
    rows = []
    for pid, fn, name in ORDER:
        attrs, dac, blink = parse(os.path.join(SRC, fn))
        if len(attrs) != 228:
            sys.exit('%s: %d attributes, expected 228' % (fn, len(attrs)))
        if blink:
            sys.exit('%s: blinking palettes are not supported' % fn)
        if dac is None:
            sys.exit('%s: no VGA DAC block' % fn)
        a = ', '.join('$%02X' % x for x in attrs)
        d = ', '.join('(%d, %d, %d)' % rgb for rgb in dac)
        rows.append("    (Id: '%s'; Name: '%s';\n     Attr: (%s);\n     Dac: (%s))"
                    % (pid, name, a, d))
    out.append(',\n'.join(rows))
    out.append('  );')
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
